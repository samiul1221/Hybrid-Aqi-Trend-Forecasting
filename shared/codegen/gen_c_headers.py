"""Generate firmware C headers from the shared single sources.

    uv run python shared/codegen/gen_c_headers.py          # write headers
    uv run python shared/codegen/gen_c_headers.py --check  # exit 1 if headers are stale

Inputs:  shared/src/aqi_shared/aqi/cpcb_breakpoints.json, shared/schema/feature_schema.yaml
Outputs: edge/firmware/aqi_node/src/aqi/cpcb_tables.gen.h
         edge/firmware/aqi_node/src/features/feature_schema.gen.h
"""

from __future__ import annotations

import sys
from pathlib import Path

from aqi_shared import aqi, schema_loader

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "edge" / "firmware" / "aqi_node" / "src"
OUT_AQI = SRC / "aqi" / "cpcb_tables.gen.h"
OUT_FS = SRC / "features" / "feature_schema.gen.h"
BANNER = "// GENERATED by shared/codegen/gen_c_headers.py from {src}. Do not edit.\n#pragma once\n"

BASELINES = ("Rbase7", "Rbase135", "base_voc", "base_nox")
AUX_SOURCES = ("dust", "wind_speed", "rain_flag")  # RF-only sources, ids 100+
AUX_BASE = 100


def _f(x: float) -> str:
    return repr(float(x))


def _arr(xs: list[str]) -> str:
    return "{" + ", ".join(xs) + "}"


def render_aqi() -> str:
    his25 = [_f(hi) for _, hi in aqi.BREAKPOINTS["pm25"]]
    his10 = [_f(hi) for _, hi in aqi.BREAKPOINTS["pm10"]]
    lines = [
        BANNER.format(src="shared/src/aqi_shared/aqi/cpcb_breakpoints.json"),
        "// CPCB NAQI PM breakpoints [S06.6]; rules in docs/decisions/0003-cpcb-aqi-rules.md",
        "// Band k uses B_lo = B_hi[k-1] (B_lo = 0 for k = 0); upper bound inclusive.",
        f"#define CPCB_N_BANDS {len(aqi.AQI_BANDS)}",
        f"#define CPCB_AQI_CAP {aqi.AQI_CAP}",
        f"#define CPCB_MIN_MEASURED_HOURS {aqi.MIN_MEASURED_HOURS}",
        f"#define CPCB_WINDOW_HOURS {aqi.WINDOW_HOURS}",
        f"#define CPCB_TREND_THRESHOLD {_f(aqi.TREND_THRESHOLD)}",
        "#define CPCB_BREAKPOINTS_VERIFIED 0  // TODO_VERIFY against the official CPCB NAQI table",
        f"static const double CPCB_AQI_LO[CPCB_N_BANDS] = {_arr([_f(lo) for lo, _ in aqi.AQI_BANDS])};",
        f"static const double CPCB_AQI_HI[CPCB_N_BANDS] = {_arr([_f(hi) for _, hi in aqi.AQI_BANDS])};",
        f"static const double CPCB_PM25_HI[CPCB_N_BANDS] = {_arr(his25)};",
        f"static const double CPCB_PM10_HI[CPCB_N_BANDS] = {_arr(his10)};",
        "static const char *const CPCB_CATEGORY[CPCB_N_BANDS] = "
        + _arr([f'"{c}"' for c in aqi.CATEGORIES])
        + ";",
    ]
    return "\n".join(lines) + "\n"


def _op_args(ch: schema_loader.Channel) -> tuple[str, str, str]:
    """(a, b, baseline) for the C channel table."""
    a = ch.op_args
    base = f"FS_BASE_{a['base'].upper()}" if "base" in a else "FS_BASE_NONE"
    if ch.op == "clip":
        return _f(a["lo"]), _f(a["hi"]), base
    if ch.op in ("offset", "scale"):
        return _f(a["value"]), "0.0", base
    if ch.op == "base_diff_scale":
        return _f(a["scale"]), "0.0", base
    if ch.op in ("cyc_sin", "cyc_cos"):
        return _f(a["period"]), "0.0", base
    return "0.0", "0.0", base


def render_schema() -> str:
    fs = schema_loader.load()
    ch_ids = {c.name: c.i for c in fs.channels}

    def src_id(name: str) -> str:
        if name in ch_ids:
            return f"FS_CH_{name.upper()}"
        return f"FS_SRC_{name.upper()}"

    rf_b_idx = [str(i) for i, f in enumerate(fs.rf_features) if not f.pm]
    lines = [
        BANNER.format(src="shared/schema/feature_schema.yaml"),
        "// Feature schema [S08] (I05). Firmware refuses models whose schema_hash != FS_SCHEMA_HASH.",
        "#include <stdint.h>",
        f'#define FS_SCHEMA_HASH "{fs.hash}"',
        f"#define FS_VERSION {fs.version}",
        f"#define FS_LOOKBACK_HOURS {fs.lookback_hours}",
        f"#define FS_HORIZONS {fs.horizons}",
        f"#define FS_N_OUTPUTS {len(fs.output_order)}  // [pm25_h1..h3, pm10_h1..h3]",
        f"#define FS_N_CHANNELS {len(fs.channels)}",
        f"#define FS_N_CHANNELS_B {len(fs.model_b_channels)}",
        f"#define FS_INSTNORM_EPS {_f(fs.raw['instnorm_eps'])}f",
        "",
        "enum fs_channel {",
        *[f"  FS_CH_{c.name.upper()} = {c.i}," for c in fs.channels],
        "};",
        "enum fs_aux_source {",
        *[f"  FS_SRC_{s.upper()} = {AUX_BASE + k}," for k, s in enumerate(AUX_SOURCES)],
        "};",
        "enum fs_op {",
        *[f"  FS_OP_{op.upper()}," for op in sorted(schema_loader.OPS)],
        "};",
        "enum fs_baseline { FS_BASE_NONE = -1, "
        + ", ".join(f"FS_BASE_{b.upper()} = {k}" for k, b in enumerate(BASELINES))
        + " };",
        "",
        "typedef struct {",
        "  const char *name;",
        "  uint8_t op;        // enum fs_op",
        "  float a, b;        // clip: lo,hi | offset/scale: value | base_diff_scale: scale | cyc: period",
        "  int8_t base;       // enum fs_baseline",
        "  uint8_t instnorm;  // per-window instance norm [S13.4]",
        "  uint8_t model_b;   // channel kept by Model B [S14]",
        "} fs_channel_def_t;",
        "",
        "static const fs_channel_def_t FS_CHANNELS[FS_N_CHANNELS] = {",
    ]
    for c in fs.channels:
        a, b, base = _op_args(c)
        lines.append(
            f'  {{"{c.name}", FS_OP_{c.op.upper()}, {a}f, {b}f, {base}, '
            f"{int(c.instnorm)}, {int(c.model_b)}}},"
        )
    lines += [
        "};",
        "",
        "// RF features [S08.3], Model A order. src: enum fs_channel or enum fs_aux_source.",
        "// lag k = x[t-k]; rmean k = mean x[t-k+1..t]; rstd k = population std of the same;",
        "// diff k = x[t]-x[t-k]; rainh k = count of rain_flag hours in x[t-k+1..t].",
        "enum fs_rf_kind { FS_RF_LAG, FS_RF_RMEAN, FS_RF_RSTD, FS_RF_DIFF, FS_RF_RAINH };",
        "typedef struct { const char *name; int16_t src; uint8_t kind; uint8_t k; uint8_t pm; }"
        " fs_rf_def_t;",
        f"#define FS_N_RF_A {len(fs.rf_features)}",
        f"#define FS_N_MODEL_B_EXTRA {len(fs.model_b_extra)}",
        f"#define FS_N_RF_B {len(fs.rf_names_b)}  // non-PM RF features + model_b_extra",
        "static const fs_rf_def_t FS_RF[FS_N_RF_A] = {",
    ]
    kind_c = {"lags": "FS_RF_LAG", "roll_mean": "FS_RF_RMEAN", "roll_std": "FS_RF_RSTD",
              "diff": "FS_RF_DIFF", "rain_hours_last": "FS_RF_RAINH"}  # fmt: skip
    for f in fs.rf_features:
        lines.append(f'  {{"{f.name}", {src_id(f.src)}, {kind_c[f.kind]}, {f.k}, {int(f.pm)}}},')
    lines += [
        "};",
        "// Model B RF input = FS_RF[FS_RF_B_FROM_A[i]] for i < FS_N_RF_B - FS_N_MODEL_B_EXTRA,",
        "// then the model_b_extra features in this order [S08.2]:",
        f"static const uint8_t FS_RF_B_FROM_A[FS_N_RF_B - FS_N_MODEL_B_EXTRA] = {_arr(rf_b_idx)};",
        "enum fs_model_b_extra {",
        *[f"  FS_MB_{n.upper()} = {k}," for k, n in enumerate(fs.model_b_extra)],
        "};",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in ((OUT_AQI, render_aqi()), (OUT_FS, render_schema())):
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    for p in stale:
        print(f"stale: {p.relative_to(ROOT)} (run shared/codegen/gen_c_headers.py)")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
